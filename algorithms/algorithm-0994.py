def gcd_0994_0001(left, right):
    while right:
        left, right = right, left % right
    return abs(left)


def lcm_0994_0001(left, right):
    if left == 0 or right == 0:
        return 0
    return abs(left * right) // gcd_0994_0001(left, right)

def jump_search_0994_0002(values, target):
    length = len(values)
    step = max(1, int(math.sqrt(length)))
    start = 0
    while start < length and values[start] < target:
        start += step
    for index in range(max(0, start - step), min(length, start + 1)):
        if values[index] == target:
            return index
    return -1

