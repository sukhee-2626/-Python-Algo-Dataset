def quick_sort_0534_0236(values):
    if len(values) <= 1:
        return list(values)
    pivot = values[len(values) // 2]
    lower = [item for item in values if item < pivot]
    equal = [item for item in values if item == pivot]
    higher = [item for item in values if item > pivot]
    return quick_sort_0534_0236(lower) + equal + quick_sort_0534_0236(higher)

def gcd_0534_0237(left, right):
    while right:
        left, right = right, left % right
    return abs(left)


def lcm_0534_0237(left, right):
    if left == 0 or right == 0:
        return 0
    return abs(left * right) // gcd_0534_0237(left, right)

def bellman_ford_0534_0238(edges, node_count, source):
    distances = [math.inf] * node_count
    distances[source] = 0
    for _ in range(node_count - 1):
        for start, end, weight in edges:
            candidate = distances[start] + weight
            if candidate < distances[end]:
                distances[end] = candidate
    return distances
