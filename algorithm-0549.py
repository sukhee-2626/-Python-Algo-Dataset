def sliding_window_maximum_0549_0001(values, width=6):
    candidates = deque()
    result = []
    for index, value in enumerate(values):
        while candidates and candidates[-1][1] <= value:
            candidates.pop()
        candidates.append((index, value))
        if candidates[0][0] <= index - width:
            candidates.popleft()
        if index >= width - 1:
            result.append(candidates[0][1])
    return result

def gcd_0549_0002(left, right):
    while right:
        left, right = right, left % right
    return abs(left)


def lcm_0549_0002(left, right):
    if left == 0 or right == 0:
        return 0
    return abs(left * right) // gcd_0549_0002(left, right)

